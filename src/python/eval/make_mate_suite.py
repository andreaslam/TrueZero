"""Generate the bundled tactics suite (mate_suite.txt) deterministically.

Positions come from seeded random games biased towards checks and captures; each is
solved exhaustively with python-chess, so every listed solution is proven:

- mate1-*: side to move mates in one; the solutions are ALL mating moves.
- mate2-*: no mate in one, and the solutions are ALL first moves that force mate in two
  against every defence.

Only positions with at most MAX_SOLUTIONS solutions are kept, so a net cannot score by
luck. Re-running with the same arguments reproduces the file exactly:

    uv run python src/python/eval/make_mate_suite.py > src/python/eval/mate_suite.txt
"""

import argparse
import random

import chess

MAX_SOLUTIONS = 2


def mates_in_one(board):
    out = []
    for mv in board.legal_moves:
        if board.gives_check(mv):
            board.push(mv)
            if board.is_checkmate():
                out.append(mv)
            board.pop()
    return out


def forces_mate_in_two(board, mv):
    """After our `mv`, every reply allows a mate in one (and there is at least one reply)."""
    board.push(mv)
    try:
        if board.is_game_over():
            return False
        for reply in list(board.legal_moves):
            board.push(reply)
            ok = bool(mates_in_one(board))
            board.pop()
            if not ok:
                return False
        return True
    finally:
        board.pop()


def random_position(rng, max_plies):
    board = chess.Board()
    for _ in range(rng.randrange(10, max_plies)):
        moves = list(board.legal_moves)
        if not moves:
            break
        forcing = [m for m in moves if board.is_capture(m) or board.gives_check(m)]
        pool = forcing if forcing and rng.random() < 0.6 else moves
        board.push(rng.choice(pool))
        if board.is_game_over():
            board.pop()
            break
    return board


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--seed", type=int, default=20261124)
    p.add_argument("--mate1", type=int, default=50)
    p.add_argument("--mate2", type=int, default=50)
    p.add_argument("--max-plies", type=int, default=120)
    args = p.parse_args()
    rng = random.Random(args.seed)

    found = {"mate1": [], "mate2": []}
    want = {"mate1": args.mate1, "mate2": args.mate2}
    seen = set()
    while any(len(found[k]) < want[k] for k in found):
        board = random_position(rng, args.max_plies)
        key = board.board_fen() + (" w" if board.turn else " b")
        if key in seen or board.is_game_over():
            continue
        seen.add(key)
        board = chess.Board(board.fen())  # drop the move stack: positions stand alone
        m1 = mates_in_one(board)
        if m1:
            kind, sols = "mate1", m1
        elif len(found["mate2"]) < want["mate2"]:
            sols = [m for m in board.legal_moves if forces_mate_in_two(board, m)]
            kind = "mate2"
        else:
            continue
        if not sols or len(sols) > MAX_SOLUTIONS or len(found[kind]) >= want[kind]:
            continue
        found[kind].append((board.fen(), sorted(m.uci() for m in sols)))

    print(f"# Generated by make_mate_suite.py --seed {args.seed}; do not edit by hand.")
    print("# <FEN> | <all solutions, standard UCI> | <category-index>")
    for kind in ("mate1", "mate2"):
        for i, (fen, sols) in enumerate(found[kind]):
            print(f"{fen} | {' '.join(sols)} | {kind}-{i:02d}")


if __name__ == "__main__":
    main()
